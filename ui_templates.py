"""Tiny deterministic HTML composition; no runtime build dependency or templating package."""
import re
import hashlib
from pathlib import Path
import ui_assets
ROOT=Path(__file__).resolve().parent

def render(root=ROOT):
    base=root/'web/templates';assets=ui_assets.manifest(root)
    def expand(name,parents=()):
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9.-]*\.html',name) or name in parents or len(parents)>10:raise ValueError('Invalid or circular UI include.')
        text=(base/name).read_text()
        def replace(match):
            indent,target=match.group(1),match.group(2)
            if target.startswith('include:'):value=expand(target.split(':',1)[1],parents+(name,)).rstrip()
            elif target=='scripts':value='\n'.join('<script src="./'+n+'?v='+hashlib.sha256((root/'static'/n).read_bytes()).hexdigest()[:12]+'"></script>' for n in assets['scripts'])
            elif target=='styles':value='\n'.join('<link rel="stylesheet" href="./'+n+'?v='+hashlib.sha256((root/'static'/n).read_bytes()).hexdigest()[:12]+'" />' for n in assets['styles'])
            else:raise ValueError('Unknown UI slot.')
            return '\n'.join(indent+line if line else '' for line in value.splitlines())
        return re.sub(r'(?m)^([ \t]*)\{\{([^{}\n]+)\}\}[ \t]*$',replace,text)
    result=expand('index.html')
    if '{{' in result or '}}' in result:raise ValueError('Unresolved UI template slot.')
    return '<!-- Generated by scripts/build-ui.py; edit web/templates/*.html. -->\n'+result.strip()+'\n'
